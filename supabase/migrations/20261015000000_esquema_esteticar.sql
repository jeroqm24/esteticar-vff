-- Esquema base de EstetiCar (tablas que ya usa la app), replicado desde el proyecto anterior.
-- No borra nada: si ya existe una tabla con el mismo nombre creada por otra cosa, se renombra a <tabla>_anterior_<fecha>.
-- Se puede ejecutar más de una vez.

do $$
declare
  t text;
  marca constant text := 'esteticar-esquema-v1';
begin
  foreach t in array array['conversations', 'appointments', 'clients', 'bot_config', 'page_views', 'api_costs', 'costs', 'ig_tokens'] loop
    if to_regclass('public.' || t) is not null
       and coalesce(obj_description(('public.' || t)::regclass, 'pg_class'), '') <> marca then
      execute format('alter table public.%I rename to %I', t, t || '_anterior_' || to_char(now(), 'YYYYMMDD'));
    end if;
  end loop;
end $$;

-- ─── conversations ───────────────────────────────────────────
create table if not exists public.conversations (
  phone               text primary key,
  history             jsonb not null default '[]'::jsonb,
  client_name         text,
  last_service        text,
  vehicle_type        text,
  vehicle_plate       text,
  client_email        text,
  cedula              text,
  updated_at          timestamptz not null default now(),
  lead_type           text,
  objection           text,
  remarketing_status  text default 'active',
  last_remarketing_at timestamptz,
  remarketing_count   int not null default 0,
  last_visit_date     timestamptz,
  bot_paused          boolean not null default false,
  direccion           text,
  custom_fields       jsonb not null default '{}'::jsonb,
  last_message_id     text,
  session_id          text,
  created_at          timestamptz not null default now()
);
create index if not exists conversations_updated_at_idx on public.conversations (updated_at desc);
create index if not exists conversations_remarketing_status_idx on public.conversations (remarketing_status);

-- ─── appointments ────────────────────────────────────────────
-- id es text: hay citas antiguas con ids que no son uuid.
create table if not exists public.appointments (
  id                 text primary key default gen_random_uuid()::text,
  service            text,
  vehicle_type       text,
  date               text,
  price_display      text,
  confirmation_code  text,
  client_name        text,
  client_phone       text,
  client_email       text,
  traslado           text,
  cedula             text,
  placa              text,
  status             text default 'pending',
  channel            text,
  created_date       timestamptz not null default now(),
  time               text,
  updated_at         timestamptz not null default now(),
  origin             text,
  lead_type          text
);
create index if not exists appointments_created_date_idx on public.appointments (created_date desc);
create index if not exists appointments_client_phone_idx on public.appointments (client_phone);
create index if not exists appointments_confirmation_code_idx on public.appointments (confirmation_code);

-- ─── clients ─────────────────────────────────────────────────
create table if not exists public.clients (
  phone         text primary key,
  name          text,
  last_service  text,
  last_date     timestamptz,
  reminded_20d  boolean not null default false,
  updated       timestamptz not null default now()
);

-- ─── bot_config ──────────────────────────────────────────────
create table if not exists public.bot_config (
  key    text primary key,
  value  text
);

-- ─── page_views ──────────────────────────────────────────────
create table if not exists public.page_views (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  session_id  text,
  page        text default '/',
  referrer    text
);
create index if not exists page_views_created_at_idx on public.page_views (created_at desc);

-- ─── api_costs ───────────────────────────────────────────────
create table if not exists public.api_costs (
  id                     bigint generated by default as identity primary key,
  created_at             timestamptz not null default now(),
  provider               text,
  model                  text,
  channel                text,
  input_tokens           int,
  output_tokens          int,
  cache_read_tokens      int not null default 0,
  cache_creation_tokens  int not null default 0,
  audio_seconds          numeric,
  cost_usd               numeric not null default 0
);
create index if not exists api_costs_created_at_idx on public.api_costs (created_at desc);

-- ─── costs (Finanzas) ────────────────────────────────────────
create table if not exists public.costs (
  id           uuid primary key default gen_random_uuid(),
  created_at   timestamptz not null default now(),
  date         date not null default (now() at time zone 'America/Bogota')::date,
  category     text,
  description  text,
  amount       numeric not null default 0
);
create index if not exists costs_date_idx on public.costs (date desc);

-- ─── ig_tokens ───────────────────────────────────────────────
create table if not exists public.ig_tokens (
  ig_user_id    text primary key,
  access_token  text not null,
  expires_at    timestamptz,
  updated_at    timestamptz not null default now()
);

-- Marca las tablas como propias para que una re-ejecución no las renombre.
comment on table public.conversations is 'esteticar-esquema-v1';
comment on table public.appointments  is 'esteticar-esquema-v1';
comment on table public.clients       is 'esteticar-esquema-v1';
comment on table public.bot_config    is 'esteticar-esquema-v1';
comment on table public.page_views    is 'esteticar-esquema-v1';
comment on table public.api_costs     is 'esteticar-esquema-v1';
comment on table public.costs         is 'esteticar-esquema-v1';
comment on table public.ig_tokens     is 'esteticar-esquema-v1';

-- ─── Seguridad (RLS) ─────────────────────────────────────────
-- El servidor usa la service_role y no pasa por RLS. El panel admin entra con sesión (authenticated).
-- Al visitante anónimo solo se le permite lo que hoy usa la web pública.
alter table public.conversations enable row level security;
alter table public.appointments  enable row level security;
alter table public.clients       enable row level security;
alter table public.bot_config    enable row level security;
alter table public.page_views    enable row level security;
alter table public.api_costs     enable row level security;
alter table public.costs         enable row level security;
alter table public.ig_tokens     enable row level security;

do $$
declare t text;
begin
  foreach t in array array['conversations', 'appointments', 'clients', 'bot_config', 'page_views', 'api_costs', 'costs'] loop
    execute format('drop policy if exists admin_todo on public.%I', t);
    execute format('create policy admin_todo on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;
-- ig_tokens: sin políticas; solo el servidor (service_role) lo lee.

-- Calendario público y bot: disponibilidad de citas.
drop policy if exists publico_leer on public.appointments;
create policy publico_leer on public.appointments for select to anon using (true);

-- Motor del chat web: memoria de clientes.
drop policy if exists publico_leer on public.clients;
drop policy if exists publico_crear on public.clients;
drop policy if exists publico_editar on public.clients;
create policy publico_leer   on public.clients for select to anon using (true);
create policy publico_crear  on public.clients for insert to anon with check (true);
create policy publico_editar on public.clients for update to anon using (true) with check (true);

-- Portafolio y bot: configuración pública.
drop policy if exists publico_leer on public.bot_config;
create policy publico_leer on public.bot_config for select to anon using (true);

-- Chat de la web: cada visitante solo toca conversaciones web_*.
drop policy if exists web_leer on public.conversations;
drop policy if exists web_crear on public.conversations;
drop policy if exists web_editar on public.conversations;
drop policy if exists web_borrar on public.conversations;
create policy web_leer   on public.conversations for select to anon using (phone like 'web\_%');
create policy web_crear  on public.conversations for insert to anon with check (phone like 'web\_%');
create policy web_editar on public.conversations for update to anon using (phone like 'web\_%') with check (phone like 'web\_%');
create policy web_borrar on public.conversations for delete to anon using (phone like 'web\_%');

-- Analítica: la web registra visitas.
drop policy if exists publico_crear on public.page_views;
create policy publico_crear on public.page_views for insert to anon with check (true);

-- Tiempo real para la analítica en vivo del panel.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'page_views') then
    alter publication supabase_realtime add table public.page_views;
  end if;
end $$;
